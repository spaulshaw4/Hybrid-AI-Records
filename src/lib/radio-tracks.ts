/** Video-title aliases that don't match a catalog track name exactly. */
const CATALOG_COVER_ALIASES: Record<string, string> = {
  red: "red at the buzz",
};

/**
 * Album artwork for a catalog/video title. Matches album titles and track
 * titles after punctuation/diacritic folding, then a short alias table.
 */
export function coverForCatalogTitle(title: string): string | undefined {
  const n = catalogKey(title);
  const aliased = CATALOG_COVER_ALIASES[n] ?? n;

  for (const album of ALBUMS) {
    if (catalogKey(album.title) === aliased) return album.cover;
  }
  for (const track of STREAM_TRACKS) {
    if (!track.cover) continue;
    if (catalogKey(track.title) === aliased) return track.cover;
  }
  return undefined;
}

/**
 * YouTube still for music-video tiles. Album art and division logos must never
 * be used here — those belong on the radio player and LivingBackground crests.
 *
 * Prefer the 1280×720 frame (`maxresdefault`). Some uploads only publish
 * 640×480 / 480×360 stills, so CoverImage walks `videoPosterFallbacks`.
 */
export function videoPosterSrc(youtubeId: string): string {
  return `https://i.ytimg.com/vi/${youtubeId}/maxresdefault.jpg`;
}

/** Lower-res YouTube stills when the HD frame is missing (YouTube 404s or a 120px stub). */
export function videoPosterFallbacks(youtubeId: string): string[] {
  return [
    `https://i.ytimg.com/vi/${youtubeId}/sddefault.jpg`,
    `https://i.ytimg.com/vi/${youtubeId}/hqdefault.jpg`,
  ];
}

/** Album artwork for radio / artist surfaces. Returns undefined when none exists. */
export function albumCoverSrc(release: { title: string; cover?: string }): string | undefined {
  return release.cover ?? coverForCatalogTitle(release.title);
}

/** Radio artwork with a YouTube fallback when a track has no album cover. */
export function catalogArtSrc(release: { id: string; title: string; cover?: string }): string {
  return albumCoverSrc(release) ?? videoPosterSrc(release.id);
}

/** Folds `@` to "at" so video titles like "The Red @ The Buzz" match the album. */
function catalogKey(value: string): string {
  return normalizeName(value.replace(/@/g, " at "));
}

/** Normalizes a title/artist for duplicate detection (case, punctuation, leading "the"). */
function normalizeName(value: string): string {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/\s*\(\d+\)\s*$/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/^the /, "")
    .trim();
}

/**
 * Removes duplicate entries from a playlist: same id, same audio source, or the
 * same song listed twice under slightly different titles (e.g. "Bill
 * Collector's Nebula" vs "The Bill Collector's Nebula"). When album is present,
 * duplicates are scoped to album+title so two albums can share a song name.
 * The first occurrence wins, so album order is preserved.
 */
export function dedupeTracks<
  T extends { id: string; title: string; artist?: string; album?: string; src?: string },
>(tracks: T[]): T[] {
  const ids = new Set<string>();
  const sources = new Set<string>();
  const identities = new Set<string>();
  const names: string[] = [];
  const out: T[] = [];

  for (const track of tracks) {
    if (ids.has(track.id)) continue;
    if (track.src && sources.has(track.src)) continue;

    const title = normalizeName(track.title);
    const album = normalizeName(track.album ?? "");
    const identity = album ? `album:${album}::${title}` : `title:${title}`;
    if (title && identities.has(identity)) continue;

    // Fallback for rows without album: collapse near-identical titles.
    if (!album && title) {
      const isDuplicateName = names.some(
        (existing) =>
          existing === title ||
          ` ${existing} `.includes(` ${title} `) ||
          ` ${title} `.includes(` ${existing} `),
      );
      if (isDuplicateName) continue;
    }

    ids.add(track.id);
    if (track.src) sources.add(track.src);
    identities.add(identity);
    if (!album) names.push(title);
    out.push(track);
  }

  return out;
}


/**
 * Mixes a playlist so it plays like a real radio rotation instead of album A
 * front to back, then album B: tracks are dealt round-robin across artists and
 * the deck each artist contributes is rotated by a stable per-artist offset, so
 * neighbours change but the result is identical on every render (SSR-safe, no
 * hydration mismatch, no reshuffle on re-render).
 */
export type MixStyle = "artist" | "genre" | "shuffle";

/** Deterministic (SSR-safe) shuffle seeded from each track title. */
export function shuffleTracks<T extends { title: string; artist?: string }>(
  tracks: T[],
  seed = 0,
): T[] {
  return [...tracks]
    .map((track, i) => {
      const key = `${seed}|${track.title}|${track.artist ?? ""}|${i}`;
      let hash = 2166136261;
      for (let c = 0; c < key.length; c++) {
        hash ^= key.charCodeAt(c);
        hash = Math.imul(hash, 16777619) >>> 0;
      }
      return { track, hash };
    })
    .sort((a, b) => a.hash - b.hash)
    .map((entry) => entry.track);
}

/** Applies the chosen rotation style to a playlist. */
export function applyMixStyle<T extends { title: string; artist?: string; album?: string; genre?: string }>(
  tracks: T[],
  style: MixStyle,
  seed = 0,
  spacing = 1,
): T[] {
  if (style === "shuffle") return shuffleTracks(tracks, seed);
  return mixTracks(tracks, style, seed, spacing);
}

export function mixTracks<T extends { title: string; artist?: string; album?: string; genre?: string }>(
  tracks: T[],
  balanceBy: "artist" | "genre" = "artist",
  seed = 0,
  /** Minimum number of other tracks between two songs from the same artist/genre. */
  spacing = 1,
): T[] {
  if (tracks.length < 3) return [...tracks];

  const decks = new Map<string, T[]>();
  for (const track of tracks) {
    const key = (balanceBy === "genre" ? track.genre : track.artist) ?? "unknown";
    const deck = decks.get(key);
    if (deck) deck.push(track);
    else decks.set(key, [track]);
  }

  // Stable pseudo-random offset per artist so each deck starts somewhere else.
  const seeded = [...decks.entries()].map(([artist, deck]) => {
    let hash = (seed * 2654435761) >>> 0;
    for (let i = 0; i < artist.length; i++) hash = (hash * 31 + artist.charCodeAt(i)) >>> 0;
    const offset = hash % deck.length;
    return { artist, hash, deck: [...deck.slice(offset), ...deck.slice(0, offset)] };
  });

  // Deal greedily: always take from the deck with the most left that isn't the
  // artist we just played, which spreads long albums across the whole rotation.
  seeded.sort((a, b) => b.deck.length - a.deck.length || a.hash - b.hash);

  const out: T[] = [];
  const cursors = new Map(seeded.map((entry) => [entry.artist, 0]));
  const window = Math.max(0, Math.min(spacing, seeded.length - 1));
  const recent: string[] = [];

  while (out.length < tracks.length) {
    const remaining = (entry: (typeof seeded)[number]) => entry.deck.length - cursors.get(entry.artist)!;
    const available = seeded.filter((entry) => remaining(entry) > 0);
    if (!available.length) break;

    // Honour the strictest spacing we can, then relax it one step at a time so
    // the rotation never stalls when one deck is all that is left.
    let pick = available[0];
    for (let w = window; w >= 0; w--) {
      const banned = new Set(recent.slice(-w));
      const candidate = available.find((entry) => !banned.has(entry.artist));
      if (candidate) {
        pick = candidate;
        break;
      }
    }
    const cursor = cursors.get(pick.artist)!;
    out.push(pick.deck[cursor]);
    cursors.set(pick.artist, cursor + 1);
    recent.push(pick.artist);
    if (recent.length > window) recent.shift();

    // Re-sort so the deck with the most left always leads the next pick.
    available.sort((a, b) => remaining(b) - remaining(a) || a.hash - b.hash);
    seeded.sort((a, b) => remaining(b) - remaining(a) || a.hash - b.hash);
  }

  return out;
}
