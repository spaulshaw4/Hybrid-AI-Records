/**
 * Stamps album cover, credits, genre and track position onto every song and
 * flattens the catalog in album order. This is the single sync point — the
 * radio player, catalog and any future surface all read the same derived data.
 */
export function syncAlbumTracks(albums: Album[]): StreamTrack[] {
  let order = 0;
  return albums.flatMap((album) =>
    album.tracks.map((track, index) => {
      order += 1;
      return {
        id: track.id,
        title: track.title,
        src: track.src,
        artist: album.artist,
        cover: album.cover,
        credits: album.credits,
        album: album.title,
        genre: album.genre,
        division: album.division,
        trackNumber: index + 1,
        trackTotal: album.tracks.length,
        priceTokens: 1,
        releaseOrder: order,
      };
    }),
  );
}

